    final_state = loop.run(
        state=state,
        dataframe=dataframe,
    )

    assert final_state.status == AgentStatus.COMPLETED

    assert len(session.observations) == 1

    assert (
        session.observations[0].tool_name
        == "numeric_statistics"
    )

    assert (
        session.observations[0].target_columns
        == ["revenue"]
    )

