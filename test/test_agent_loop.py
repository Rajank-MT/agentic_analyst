class SequentialMockLLM(AgentLLM):

    def __init__(self, actions):
        self.actions = actions
        self.index = 0

    def decide(self, state, observations):
        action = self.actions[self.index]

        if self.index < len(self.actions) - 1:
            self.index += 1

        return action


class FakeInsightGenerator(InsightGenerator):

    def __init__(self):
        self.called = False
        self.received_observations = []

    def generate(
        self,
        state,
        observations: list[AgentObservation],
    ) -> BusinessInsightReport:

        self.called = True
        self.received_observations = observations

        return BusinessInsightReport(
            insights=[
                BusinessInsight(
                    title="Revenue statistics generated",
                    finding="Revenue statistics were successfully calculated.",
                    evidence=[
                        InsightEvidence(
                            execution_index=0,
                            fact="Revenue statistics were generated by the numeric statistics tool.",
                        )
                    ],
                    business_impact="Provides a baseline for understanding revenue performance.",
                    recommendation="Use the revenue baseline for further business analysis.",
                    priority=InsightPriority.MEDIUM,
                )
            ]
        )


def test_agent_loop_generates_insights_on_finish():

    dataframe = pd.DataFrame(
        {
            "revenue": [1000, 1500, 700, 2200, 1800],
        }
    )

    dataset_profile = profile_dataset(
        dataframe=dataframe,
        dataset_name="customers",
    )

    metric_profiles = [
        discover_metric_role(column)
        for column in dataset_profile.columns
    ]

    registry = build_analysis_tool_registry()

    state = create_agent_state(
        user_goal="Find important business insights.",
        dataset_names=["customers"],
        metric_profiles=metric_profiles,
        available_tools=registry.tools,
    )

    run_statistics_action = AgentAction(
        action_type=AgentActionType.RUN_TOOL,
        tool_call={
            "tool_name": "numeric_statistics",
            "target_columns": ["revenue"],
            "reasoning": "Calculate the revenue baseline.",
        },
        reason="Analyze revenue.",
    )

    finish_action = AgentAction(
        action_type=AgentActionType.FINISH,
        reason="Sufficient evidence has been collected.",
    )

    llm = SequentialMockLLM(
        actions=[
            run_statistics_action,
            finish_action,
        ]
    )

    fake_generator = FakeInsightGenerator()

    loop = AgentLoop(
        llm=llm,
        registry=registry,
        max_steps=3,
        insight_generator=fake_generator,
    )

    final_state = loop.run(
        state=state,
        dataframe=dataframe,
    )

    assert fake_generator.called is True

    assert len(fake_generator.received_observations) == 1

    assert final_state.status.value == "completed"

    assert len(final_state.insights) == 1

    assert (
        final_state.insights[0].title
        == "Revenue statistics generated"
    )

    assert final_state.insights[0].evidence[0].execution_index == 0

def test_agent_loop_fails_when_max_steps_reached():

    dataframe = pd.DataFrame(
        {
            "revenue": [1000, 1500, 700, 2200, 1800],
        }
    )

    dataset_profile = profile_dataset(
        dataframe=dataframe,
        dataset_name="customers",
    )

    metric_profiles = [
        discover_metric_role(column)
        for column in dataset_profile.columns
    ]

    registry = build_analysis_tool_registry()

    state = create_agent_state(
        user_goal="Find important business insights.",
        dataset_names=["customers"],
        metric_profiles=metric_profiles,
        available_tools=registry.tools,
    )

    run_statistics_action = AgentAction(
        action_type=AgentActionType.RUN_TOOL,
        tool_call={
            "tool_name": "numeric_statistics",
            "target_columns": ["revenue"],
            "reasoning": "Analyze revenue.",
        },
        reason="Analyze revenue.",
    )

    # The mock LLM will NEVER return FINISH.
    llm = SequentialMockLLM(
        actions=[
            run_statistics_action,
        ]
    )

    loop = AgentLoop(
        llm=llm,
        registry=registry,
        max_steps=1,
    )

    final_state = loop.run(
        state=state,
        dataframe=dataframe,
    )

    assert final_state.status == AgentStatus.MAX_STEPS_REACHED

    assert len(final_state.executions) >= 1

    assert final_state.executions[-1].tool_name == "agent_loop"

    assert final_state.executions[-1].success is False

    assert "Maximum reasoning steps" in final_state.executions[-1].error


